import createLumVibeAudio from './wasm/lumvibe_audio.js';

interface LvaModule {
  HEAPF32: Float32Array; HEAP32: Int32Array;
  _malloc(n: number): number; _free(p: number): void;
  _lva_process(params: number, nParams: number,
               voice: number, voiceFrames: number, voiceRate: number, voiceCh: number,
               beat: number, beatFrames: number, beatRate: number, beatCh: number,
               cb: number, user: number, outPcm: number, outFrames: number, outRate: number, outCh: number): number;
  _lva_free(p: number): void;
  _lva_last_error(): number;
  _lva_has_rnnoise(): number;
  UTF8ToString(p: number): string;
}

let modulePromise: Promise<LvaModule> | null = null;
const getModule = () => (modulePromise ??= (createLumVibeAudio() as Promise<LvaModule>));

export async function hasNoiseModel(): Promise<boolean> { return (await getModule())._lva_has_rnnoise() === 1; }

/** Decode mp3/m4a/wav/ogg with the browser's own decoder to interleaved float PCM (1-2 channels). */
async function decode(bytes: ArrayBuffer): Promise<{ pcm: Float32Array; rate: number; channels: number }> {
  // OfflineAudioContext avoids the "must be started by a user gesture" rule of a normal AudioContext
  const ctx = new OfflineAudioContext(2, 1, 48000);
  const buf = await ctx.decodeAudioData(bytes.slice(0));
  const ch = Math.min(2, buf.numberOfChannels);
  const n = buf.length;
  const pcm = new Float32Array(n * ch);
  for (let c = 0; c < ch; c++) {
    const src = buf.getChannelData(c);
    for (let i = 0; i < n; i++) pcm[i * ch + c] = src[i];
  }
  return { pcm, rate: buf.sampleRate, channels: ch };
}

function putF32(M: LvaModule, a: Float32Array): number {
  const p = M._malloc(a.length * 4);
  M.HEAPF32.set(a, p >> 2);        // read M.HEAPF32 AFTER malloc: memory growth replaces the view
  return p;
}

function encodeWav(pcm: Float32Array, rate: number, channels: number): Blob {
  const n = pcm.length, out = new DataView(new ArrayBuffer(44 + n * 2));
  const w = (o: number, s: string) => { for (let i = 0; i < s.length; i++) out.setUint8(o + i, s.charCodeAt(i)); };
  w(0, 'RIFF'); out.setUint32(4, 36 + n * 2, true); w(8, 'WAVE'); w(12, 'fmt ');
  out.setUint32(16, 16, true); out.setUint16(20, 1, true); out.setUint16(22, channels, true);
  out.setUint32(24, rate, true); out.setUint32(28, rate * channels * 2, true); out.setUint16(32, channels * 2, true); out.setUint16(34, 16, true);
  w(36, 'data'); out.setUint32(40, n * 2, true);
  for (let i = 0; i < n; i++) out.setInt16(44 + i * 2, Math.max(-32768, Math.min(32767, Math.round(pcm[i] * 32767))), true);
  return new Blob([out], { type: 'audio/wav' });
}

export interface WebBakeResult { blob: Blob; durationSec: number; sampleRate: number; channels: number }

/** voice / beat: the raw bytes of the audio files (File.arrayBuffer(), fetch().arrayBuffer() ...). */
export async function bakeAudioStudioWeb(args: {
  voice: ArrayBuffer; beat?: ArrayBuffer | null; params: number[];
}): Promise<WebBakeResult> {
  const M = await getModule();
  const v = await decode(args.voice);
  const b = args.beat ? await decode(args.beat) : null;

  const ptrs: number[] = [];
  const keep = (p: number) => { ptrs.push(p); return p; };
  try {
    const pParams = keep(putF32(M, new Float32Array(args.params)));
    const pVoice = keep(putF32(M, v.pcm));
    const pBeat = b ? keep(putF32(M, b.pcm)) : 0;
    const out = keep(M._malloc(16));                         // [float* pcm][int frames][int rate][int channels]
    const rc = M._lva_process(pParams, args.params.length,
      pVoice, v.pcm.length / v.channels, v.rate, v.channels,
      pBeat, b ? b.pcm.length / b.channels : 0, b ? b.rate : 0, b ? b.channels : 0,
      0, 0, out, out + 4, out + 8, out + 12);
    if (rc !== 0) throw new Error(M.UTF8ToString(M._lva_last_error()) || 'Audio processing failed');

    const pcmPtr = M.HEAP32[out >> 2], frames = M.HEAP32[(out >> 2) + 1], rate = M.HEAP32[(out >> 2) + 2], ch = M.HEAP32[(out >> 2) + 3];
    const pcm = M.HEAPF32.slice(pcmPtr >> 2, (pcmPtr >> 2) + frames * ch);
    M._lva_free(pcmPtr);
    return { blob: encodeWav(pcm, rate, ch), durationSec: frames / rate, sampleRate: rate, channels: ch };
  } finally {
    for (const p of ptrs) M._free(p);
  }
}
